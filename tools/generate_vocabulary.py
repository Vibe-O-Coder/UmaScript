"""Generate compiler/editor vocabulary and the reference table from palavras.toml."""
from pathlib import Path
import json, tomllib, re
ROOT=Path(__file__).resolve().parents[1]
data=tomllib.loads((ROOT/'palavras.toml').read_text(encoding='utf-8'))
words={**data['tipos'],**data['palavras'],**data['modulos']}
q=lambda s:json.dumps(s,ensure_ascii=True)
header='#pragma once\n// Generated by tools/generate_vocabulary.py.\n'
header+='inline const std::string umaVersion='+q(data['version'])+';\n'
header+='inline const std::unordered_map<std::string,std::string> vocabularyAliases={'+','.join('{'+q(b)+','+q(a)+'}' for a,b in words.items() if a!=b)+'};\n'
header+='inline const std::unordered_map<std::string,std::string> vocabularyClassic={'+','.join('{'+q(a)+','+q(b)+'}' for a,b in words.items())+'};\n'
header+='inline const std::unordered_set<std::string> primitives={'+','.join(map(q,data['tipos']))+'};\n'
header+='inline const std::unordered_set<std::string> keywords={'+','.join(map(q,{**data['palavras'],**data['modulos']}))+'};\n'
(ROOT/'src/vocabulary.hpp').write_text(header,encoding='utf-8')
(ROOT/'vscode-extension/src/vocabulary.json').write_text(json.dumps({'version':data['version'],'words':words},ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
p=ROOT/'vscode-extension/package.json';manifest=json.loads(p.read_text());manifest['version']=data['version'];p.write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
p=ROOT/'vscode-extension/syntaxes/umascript.tmLanguage.json';grammar=json.loads(p.read_text())
# A generated rule covers both dialects, including ownership qualifiers.
rule={'name':'keyword.control.umascript','match':r'\b(?:'+'|'.join(sorted(set(words)|set(words.values())))+r')\b'}
grammar['patterns']=[x for x in grammar['patterns'] if x.get('name')!='keyword.control.umascript']+[rule]
p.write_text(json.dumps(grammar,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
table='# Vocabulario 3.1\n\nGerado de `palavras.toml`. Os dois dialetos usam a mesma gramatica.\n\n| Uma | Classico |\n| --- | --- |\n'+''.join(f'| `{a}` | `{b}` |\n' for a,b in words.items())
(ROOT/'docs/VOCABULARIO.md').write_text(table,encoding='utf-8')
snippets_path=ROOT/'vscode-extension/snippets/umascript.json'
snippets=json.loads(snippets_path.read_text(encoding='utf-8'))
for uma,classic in words.items():
    snippets['vocabulary-'+uma]={'prefix':uma,'body':[uma],'description':uma+' = '+classic}
snippets_path.write_text(json.dumps(snippets,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
source=(ROOT/'src/language.hpp').read_text(encoding='utf-8')
native_table=source.split('const map<string, NativeSignature> standardNatives = {',1)[1].split('\n};',1)[0]
natives=[]
for name,result,parameters,documentation in re.findall(r'\{"([^"]+)",\s*\{"([^"]+)",\s*\{([^}]*)\},\s*"([^"]*)"\}\}',native_table):
    types=re.findall(r'"([^"]+)"',parameters)
    natives.append({'name':name,'type':result,'signature':result+' '+name+'('+', '.join(t+' arg'+str(i+1) for i,t in enumerate(types))+')','documentation':documentation,'kind':'function','builtin':True})
(ROOT/'vscode-extension/src/native-data.json').write_text(json.dumps(natives,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print('Vocabulary generated:',data['version'])
